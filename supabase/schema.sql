-- Run once in Supabase SQL Editor. One project = one teacher group/school.
begin;
create table if not exists public.teacher_roles (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.teacher_roles enable row level security;
revoke all on public.teacher_roles from anon, authenticated;
grant select on public.teacher_roles to authenticated;
drop policy if exists teacher_self_read on public.teacher_roles;
create policy teacher_self_read on public.teacher_roles for select to authenticated
using (user_id = (select auth.uid()));

create table if not exists public.student_submissions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  student_number text not null check (char_length(btrim(student_number)) between 1 and 30),
  grade_term text not null check (char_length(btrim(grade_term)) between 1 and 40),
  course_unit text not null check (char_length(btrim(course_unit)) between 1 and 100),
  activity_title text not null check (char_length(btrim(activity_title)) between 1 and 160),
  evidence text not null check (char_length(btrim(evidence)) between 1 and 1400),
  project text not null default '' check (char_length(project) <= 900),
  contribution text not null check (char_length(btrim(contribution)) between 1 and 1200),
  problem_solving text not null default '' check (char_length(problem_solving) <= 1200),
  reflection text not null check (char_length(btrim(reflection)) between 1 and 900),
  created_at timestamptz not null default now()
);
create index if not exists submissions_owner_date on public.student_submissions(user_id, created_at desc);
create index if not exists submissions_date on public.student_submissions(created_at desc);
alter table public.student_submissions enable row level security;
revoke all on public.student_submissions from anon, authenticated;
grant select on public.student_submissions to authenticated;
-- Identity, ID and timestamp are generated by the database, never supplied by clients.
grant insert (student_number, grade_term, course_unit, activity_title, evidence, project, contribution, problem_solving, reflection)
on public.student_submissions to authenticated;
drop policy if exists student_insert_own on public.student_submissions;
create policy student_insert_own on public.student_submissions for insert to authenticated
with check (user_id = (select auth.uid()));
drop policy if exists student_or_teacher_read on public.student_submissions;
create policy student_or_teacher_read on public.student_submissions for select to authenticated
using (user_id = (select auth.uid()) or exists (
  select 1 from public.teacher_roles where user_id = (select auth.uid())
));
commit;

